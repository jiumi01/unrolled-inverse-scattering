# -*- coding: utf-8 -*-
"""
run_geometry_sweep.py — Experiment A: cross-geometry generalization.

Trains a NEW K=8 constrained unrolling on a structurally distinct geometry
family (axis-aligned rectangles) and evaluates, on all four families:

    ell    : 1-3 ellipses/rings   (the paper's existing family, isp_core.random_contrast)
    rect   : 1-3 rotated rectangles with sharp corners
    stripe : 1-3 full-span horizontal/vertical bands
    blob   : 1-3 irregular contours (angular-modulated radial blobs)

Train/test instances are isolated by seed (train seed=1, test seed=2, exactly
the paper's split convention); no object instance appears in both sets and no
family shares instances with another. For the ell family we reuse the paper's
cached datasets (results/cache), so the cross-family numbers are quoted against
the SAME test set the paper reports. rect/stripe/blob are generated by this
script under results/cache_geom/ with a family tag in the cache key, because
the isp_core cache key does not encode the geometry family and an untagged
regeneration would silently serve the ellipse data.

Protocol mirrors run_experiments.py / run_contrast_sweep.py (same grid 32x32,
dx=0.02, 8 incidences, 32 receivers, chi in [0.25, 0.5], snr: train 20 dB,
test 300 dB clean). Metrics per (model, family):

  * RRE at trained depth K=8 (in-family vs cross-family)
  * depth sweep D in {1,2,4,8,16,24,50,100}: RRE + max|chi| + max|w| (boundedness)
  * beta0_meas = max(chi_test) * ||Gb||_2 (certificate hypothesis value)

Models: (i) a rect-trained network trained here (ckpt_rect_K8.pt);
        (ii) the existing ellipse-trained checkpoint ckpt_constrained_K8.pt.

Output: results/geometry_sweep.json + results/ckpt_rect_K8.pt + printed summary.
"""
import json, os, sys, time
import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from isp_core import (build_matrices, make_dirs, incident_fields, forward_exact,
                      add_noise, random_contrast, make_dataset, UnrolledISP)

torch.manual_seed(1234)
np.random.seed(1234)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.normpath(os.path.join(HERE, "..", "results"))
CACHE_GEOM = os.path.join(RES, "cache_geom")
DEV = "cuda" if torch.cuda.is_available() else "cpu"
NX = NY = 32
N_INC = 8
N_RX = 32
KB = 2 * np.pi
DX = 0.02
CKPT_ELL = os.path.join(RES, "ckpt_constrained_K8.pt")
FAMILIES = ["ell", "rect", "stripe", "blob"]
DEPTHS = [1, 2, 4, 8, 16, 24, 50, 100]
N_TR, SEED_TR, SNR_TR = 300, 1, 20.0
N_TE, SEED_TE, SNR_TE = 100, 2, 300.0


# ------------------------------------------------------------- geometry ----

def _grid(nx, ny):
    x = (np.arange(nx) - (nx - 1) / 2) * DX
    y = (np.arange(ny) - (ny - 1) / 2) * DX
    X, Y = np.meshgrid(x, y, indexing="ij")
    return X, Y


def random_contrast_rect(nx, ny, rng, chi_max=0.5):
    """1-3 rotated rectangles with sharp corners, chi in [0.25, chi_max]."""
    X, Y = _grid(nx, ny)
    chi = np.zeros(nx * ny)
    for _ in range(rng.integers(1, 4)):
        cx, cy = rng.uniform(-0.22, 0.22, 2)
        wx, wy = rng.uniform(0.08, 0.20, 2)          # half-widths
        rot = rng.uniform(0, np.pi)
        Xr = (X - cx) * np.cos(rot) + (Y - cy) * np.sin(rot)
        Yr = -(X - cx) * np.sin(rot) + (Y - cy) * np.cos(rot)
        m = ((np.abs(Xr) < wx) & (np.abs(Yr) < wy)).ravel()
        chi[m] = np.maximum(chi[m], rng.uniform(0.25, chi_max))
    return chi


def random_contrast_stripe(nx, ny, rng, chi_max=0.5):
    """1-3 full-span horizontal or vertical bands, chi in [0.25, chi_max]."""
    X, Y = _grid(nx, ny)
    chi = np.zeros(nx * ny)
    for _ in range(rng.integers(1, 4)):
        horizontal = rng.random() < 0.5
        pos = rng.uniform(-0.22, 0.22)
        halfw = rng.uniform(0.03, 0.10)
        if horizontal:
            m = (np.abs(Y - pos) < halfw).ravel()
        else:
            m = (np.abs(X - pos) < halfw).ravel()
        chi[m] = np.maximum(chi[m], rng.uniform(0.25, chi_max))
    return chi


def random_contrast_blob(nx, ny, rng, chi_max=0.5):
    """1-3 irregular contours: radius = a0 + a1*cos(k*angle+ph), chi in [0.25, chi_max]."""
    X, Y = _grid(nx, ny)
    chi = np.zeros(nx * ny)
    for _ in range(rng.integers(1, 4)):
        cx, cy = rng.uniform(-0.2, 0.2, 2)
        ang = np.arctan2(Y - cy, X - cx)
        rad = np.hypot(X - cx, Y - cy)
        a0 = rng.uniform(0.10, 0.20)
        k = rng.integers(3, 7)
        a1 = rng.uniform(0.03, 0.10)
        ph = rng.uniform(0, 2 * np.pi)
        m = (rad < (a0 + a1 * np.cos(k * ang + ph))).ravel()
        chi[m] = np.maximum(chi[m], rng.uniform(0.25, chi_max))
    return chi


GEN = {"ell": random_contrast, "rect": random_contrast_rect,
       "stripe": random_contrast_stripe, "blob": random_contrast_blob}


def gen_dataset(fam, n, seed, snr_db):
    """Generate (or load) one family's dataset under CACHE_GEOM.

    The rng consumption order mirrors isp_core.make_dataset exactly: per sample
    the geometry draws come first, then add_noise draws.  The family name is
    part of the cache key, so families can never be served each other's data.
    """
    key = "ds_%s_n%d_nx%d_ny%d_seed%d_snr%s" % (fam, n, NX, NY, seed, snr_db)
    path = os.path.join(CACHE_GEOM, key + ".npz")
    if os.path.exists(path):
        z = np.load(path)
        chis, ys, Ei_ = z["chis"], z["ys"], z["Ei"]
        if chis.shape[0] == n and Ei_.shape == (N_INC, NX * NY):
            return chis, ys, Ei_
    Ei = incident_fields(pts, dirs, kb)
    rng = np.random.default_rng(seed)
    chis, ys = [], []
    for _ in range(n):
        chi = GEN[fam](NX, NY, rng)
        _, _, y = forward_exact(Gb, Gs, Ei, chi)
        ys.append(add_noise(y, snr_db, rng))
        chis.append(chi)
    chis = np.stack(chis).astype(np.float32)
    ys = np.stack(ys).astype(np.complex64)
    os.makedirs(CACHE_GEOM, exist_ok=True)
    try:
        with open(path + ".tmp%d" % os.getpid(), "wb") as fh:
            np.savez_compressed(fh, chis=chis, ys=ys, Ei=Ei)
        os.replace(path + ".tmp%d" % os.getpid(), path)
    except Exception:
        pass
    return chis, ys, Ei


def init_state(model, y, batch):
    with torch.no_grad():
        Ei = model.Ei.unsqueeze(0).expand(batch, -1, -1)
        chi0 = model._cg_ls(Ei, y)
        chi0 = chi0.clamp(0.0, model.chi_max)
        w0 = chi0.unsqueeze(1) * model.Ei.unsqueeze(0)
    return chi0, w0


def rre(chi_hat, chi_true):
    num = ((chi_hat - chi_true) ** 2).sum(dim=1).sqrt()
    den = (chi_true ** 2).sum(dim=1).sqrt() + 1e-12
    return (num / den).mean().item()


@torch.no_grad()
def eval_rre(model, chi_t, y_t, batch=50):
    model.eval()
    errs = []
    for i in range(0, chi_t.shape[0], batch):
        chi_b = chi_t[i:i + batch]
        y_b = y_t[i:i + batch]
        chi0, w0 = init_state(model, y_b, chi_b.shape[0])
        chi_k, _ = model(chi0, w0, y_b)
        errs.append(rre(chi_k, chi_b))
    return float(np.mean(errs))


@torch.no_grad()
def depth_sweep(model, chi_t, y_t, depths, batch=50):
    model.eval()
    K = model.K
    out = {}
    for i in range(0, chi_t.shape[0], batch):
        chi_b = chi_t[i:i + batch]
        y_b = y_t[i:i + batch]
        chi, w = init_state(model, y_b, chi_b.shape[0])
        for d in range(1, max(depths) + 1):
            chi, w = model.layer((d - 1) % K, chi, w, y_b)
            if d in depths:
                out.setdefault(d, {"rre": [], "max_chi": [], "max_w": []})
                out[d]["rre"].append(rre(chi, chi_b))
                out[d]["max_chi"].append(chi.abs().max().item())
                out[d]["max_w"].append(w.abs().max().item())
    return {str(d): {"rre": float(np.mean(v["rre"])),
                     "max_chi": float(np.max(v["max_chi"])),
                     "max_w": float(np.max(v["max_w"]))}
            for d, v in out.items()}


def train(model, chi_tr, y_tr, epochs=40, bs=16, lr=1e-3, lam_data=0.5, log=print):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    n = chi_tr.shape[0]
    model.train()
    for ep in range(epochs):
        perm = torch.randperm(n)
        tot = 0.0
        for i in range(0, n, bs):
            idx = perm[i:i + bs]
            chi_b = chi_tr[idx].to(DEV)
            y_b = y_tr[idx].to(DEV)
            chi0, w0 = init_state(model, y_b, chi_b.shape[0])
            chi_k, w_k = model(chi0, w0, y_b)
            Gs_w = torch.matmul(model.Gs, w_k.reshape(-1, w_k.shape[-1]).T).T.reshape(y_b.shape)
            loss = ((chi_k - chi_b) ** 2).mean() + lam_data * (Gs_w - y_b).abs().pow(2).mean()
            opt.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1e3)
            opt.step()
            model.clamp_sn()
            tot += loss.item()
        if ep % 10 == 0 or ep == epochs - 1:
            log(f"    ep{ep:03d} loss={tot / max(1, (n // bs)): .5f}")
    return model


def family_stats(chi):
    m = chi > 0
    nz = m.mean()
    return {"nonzero_frac": float(nz), "max_chi": float(chi.max())}


def main():
    global Gb, Gs, pts, dirs, kb
    t0 = time.time()
    log = open(os.path.join(RES, "geometry_sweep_log.txt"), "w", buffering=1)
    def say(*a):
        msg = " ".join(str(x) for x in a)
        print(msg, flush=True)
        log.write(msg + "\n")
    os.makedirs(RES, exist_ok=True)
    Gb, Gs, pts, rx = build_matrices(NX, NY, dx=DX)
    dirs = make_dirs(N_INC)
    kb = KB
    gb2 = float(np.linalg.norm(Gb, 2))
    say(f"[env] ||Gb||2={gb2:.4f} device={DEV}")

    # ---- datasets -----------------------------------------------------------
    data = {}
    for fam in FAMILIES:
        if fam == "ell":
            # reuse the paper's cached datasets so cross-family numbers are quoted
            # against the exact same test set the paper reports
            chi_tr, y_tr, _ = make_dataset(N_TR, Gb, Gs, pts, dirs, kb, NX, NY,
                                           seed=SEED_TR, snr_db=SNR_TR, cache=True)
            chi_te, y_te, Ei = make_dataset(N_TE, Gb, Gs, pts, dirs, kb, NX, NY,
                                            seed=SEED_TE, snr_db=SNR_TE, cache=True)
        else:
            chi_tr, y_tr, _ = gen_dataset(fam, N_TR, SEED_TR, SNR_TR)
            chi_te, y_te, Ei = gen_dataset(fam, N_TE, SEED_TE, SNR_TE)
        data[fam] = {"tr": (torch.from_numpy(chi_tr).float(),
                            torch.from_numpy(y_tr).to(torch.complex64)),
                     "te": (torch.from_numpy(chi_te).float(),
                            torch.from_numpy(y_te).to(torch.complex64))}
        say(f"[data] {fam}: train nz={family_stats(chi_tr)['nonzero_frac']:.3f} "
            f"maxchi={family_stats(chi_tr)['max_chi']:.3f} | test nz="
            f"{family_stats(chi_te)['nonzero_frac']:.3f} maxchi="
            f"{family_stats(chi_te)['max_chi']:.3f}")

    # structural distinctness: pairwise mask disagreement between families
    masks = {fam: (data[fam]["te"][0].numpy() > 0) for fam in FAMILIES}
    for a in FAMILIES:
        for b in FAMILIES:
            if a < b:
                same = np.array_equal(masks[a], masks[b])
                say(f"[geom] mask({a}) == mask({b}): {same}")

    # ---- models -------------------------------------------------------------
    Ei_np = np.asarray(incident_fields(pts, dirs, kb))
    m_rect = UnrolledISP(8, Gb, Gs, Ei_np, NX, NY, N_INC, mode="constrained",
                         eps_bar=0.03, proj=True).to(DEV)
    say("[train] rect family, K=8, constrained, 40 epochs (bs16, lr1e-3)...")
    m_rect = train(m_rect, *data["rect"]["tr"], log=say)
    torch.save(m_rect.state_dict(), os.path.join(RES, "ckpt_rect_K8.pt"))
    say("[train] done -> results/ckpt_rect_K8.pt")

    m_ell = UnrolledISP(8, Gb, Gs, Ei_np, NX, NY, N_INC, mode="constrained",
                        eps_bar=0.03, proj=True).to(DEV)
    m_ell.load_state_dict(torch.load(CKPT_ELL, map_location=DEV))
    m_ell.eval()
    say("[model] loaded existing ellipse-trained ckpt_constrained_K8.pt")

    # ---- evaluate: (model, family) -----------------------------------------
    rec = {"gb_norm2": gb2, "ckpt_rect": "ckpt_rect_K8.pt",
           "ckpt_ell": "ckpt_constrained_K8.pt", "device": DEV}
    for tag, m in (("rect_model", m_rect), ("ell_model", m_ell)):
        rec[tag] = {}
        for fam in FAMILIES:
            chi_d = data[fam]["te"][0].to(DEV)
            y_d = data[fam]["te"][1].to(DEV)
            r = {"beta0_meas": float(chi_d.max().item() * gb2),
                 "rre_K8": eval_rre(m, chi_d, y_d)}
            r["depth"] = depth_sweep(m, chi_d, y_d, DEPTHS)
            d8, d100 = r["depth"]["8"], r["depth"]["100"]
            r["depth_K8_vs_100"] = [d8["rre"], d100["rre"]]
            rec[tag][fam] = r
            say(f"[{tag}] {fam}: beta0_meas={r['beta0_meas']:.4f} "
                f"rre_K8={r['rre_K8']:.4f} | D=8 rre={d8['rre']:.4f} "
                f"D=100 rre={d100['rre']:.4f} maxchi={d100['max_chi']:.3f} "
                f"maxw={d100['max_w']:.3f}")

    with open(os.path.join(RES, "geometry_sweep.json"), "w") as f:
        json.dump({"families": FAMILIES, "depths": DEPTHS, "protocol":
                   "mirrors run_experiments.py (train seed1 snr20 / test seed2 snr300, "
                   "chi in [0.25,0.5]); instances isolated by seed; ell family is the "
                   "paper's cached dataset",
                   "records": rec}, f, indent=1)
    say(f"[done] total {time.time() - t0:.0f}s -> results/geometry_sweep.json")
    log.close()


if __name__ == "__main__":
    main()
