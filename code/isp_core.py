# -*- coding: utf-8 -*-
"""
isp_core.py — 2D TM inverse scattering: MoM discretization, dataset generation,
unrolled network (constrained / unconstrained / classical), gain estimator.

Layer map (see docs/02_理论推导.md):
  w+   = (1-a) w + a * chi * (Ei + Gb w)          (damped Born field step)
  E+   = Ei + Gb w+
  chi+ = (1-g) chi + g * Chat(w+, E+; y)          (damped LS contrast step)
  chi+ = chi+ + H_k(features)                      (learned correction)
Constrained H_k = eps_bar * tanh(CNN with spectral-norm clamped kernels).
"""
import hashlib, os
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from scipy.special import hankel2

# ---------------------------------------------------------------- physics ---

def green_2d(r1, r2, kb):
    d = np.linalg.norm(r1[:, None, :] - r2[None, :, :], axis=-1)
    return -1j / 4.0 * hankel2(0, kb * d)

def build_matrices(nx=32, ny=32, dx=0.1, lam=1.0, n_rx=32):
    kb = 2 * np.pi / lam
    x = (np.arange(nx) - (nx - 1) / 2) * dx
    y = (np.arange(ny) - (ny - 1) / 2) * dx
    X, Y = np.meshgrid(x, y, indexing='ij')
    pts = np.stack([X.ravel(), Y.ravel()], axis=1)
    n = nx * ny
    dA = dx * dx
    a_eq = dx / np.sqrt(np.pi)
    g_self = -1j / 4.0 * (1 + (2j / np.pi) *
                          (np.log(kb * a_eq / 2) + 0.5772156649 - 1j * np.pi / 2))
    G = green_2d(pts, pts, kb)
    np.fill_diagonal(G, g_self)
    Gb = kb ** 2 * dA * G
    th = np.linspace(0, 2 * np.pi, n_rx, endpoint=False)
    rx = 2.0 * np.stack([np.cos(th), np.sin(th)], axis=1)
    Gs = kb ** 2 * dA * green_2d(rx, pts, kb)
    return Gb, Gs, pts, rx

def make_dirs(n_inc=8):
    th = np.linspace(0, 2 * np.pi, n_inc, endpoint=False) + np.pi / n_inc
    return np.stack([np.cos(th), np.sin(th)], axis=1)

def incident_fields(pts, dirs, kb):
    return np.exp(-1j * kb * (pts @ dirs.T)).T.astype(np.complex128)   # (I,n)

# ------------------------------------------------------------- dataset ------

def random_contrast(nx, ny, rng, dx=0.02, chi_max=0.5):
    x = (np.arange(nx) - (nx - 1) / 2) * dx
    y = (np.arange(ny) - (ny - 1) / 2) * dx
    X, Y = np.meshgrid(x, y, indexing='ij')
    chi = np.zeros(nx * ny)
    for _ in range(rng.integers(1, 4)):
        cx, cy = rng.uniform(-0.22, 0.22, 2)
        ax, ay = rng.uniform(0.10, 0.25, 2)
        rot = rng.uniform(0, np.pi)
        Xr = (X - cx) * np.cos(rot) + (Y - cy) * np.sin(rot)
        Yr = -(X - cx) * np.sin(rot) + (Y - cy) * np.cos(rot)
        R2 = (Xr / ax) ** 2 + (Yr / ay) ** 2
        m = (R2 < 1.0) & (R2 > 0.35) if rng.random() < 0.25 else (R2 < 1.0)
        m = m.ravel()
        chi[m] = np.maximum(chi[m], rng.uniform(0.25, chi_max))
    return chi

def forward_exact(Gb, Gs, Ei, chi):
    n = chi.size
    # Lippmann--Schwinger: (I - G_b diag(chi)) E = E^i  (paper eq:ls/eq:discrete)
    A = np.eye(n) - Gb * chi[None, :]
    E = np.linalg.solve(A, Ei.T)          # (n, I)
    w = chi[:, None] * E
    y = (Gs @ w).T                        # (I, n_rx)
    return E.T, w.T, y

def add_noise(y, snr_db, rng):
    p = np.mean(np.abs(y) ** 2)
    s = p / (10 ** (snr_db / 10))
    n = np.sqrt(s / 2) * (rng.standard_normal(y.shape) + 1j * rng.standard_normal(y.shape))
    return y + n

CACHE = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                      "..", "results", "cache"))


def _ds_key(n_samples, Gb, Gs, Ei, nx, ny, seed, snr_db):
    """Content-addressed key: the discretisation matrices enter as a digest, so a change
    of dx / n_inc / geometry can never be served a stale dataset."""
    h = hashlib.md5()
    h.update(np.ascontiguousarray(Gb, dtype=np.complex128).tobytes())
    h.update(np.ascontiguousarray(Gs, dtype=np.complex128).tobytes())
    h.update(np.ascontiguousarray(Ei, dtype=np.complex128).tobytes())
    return "ds_n%d_nx%d_ny%d_seed%d_snr%s_%s" % (
        n_samples, nx, ny, seed, snr_db, h.hexdigest()[:10])


def make_dataset(n_samples, Gb, Gs, pts, dirs, kb, nx, ny, seed, snr_db=20.0,
                 cache=True):
    """Generate (or load) a deterministic dataset.

    A single sample costs one 1024x1024 complex solve, ~0.25 s single-threaded, so the
    400 samples used by the audit take ~100 s -- but they were being regenerated by every
    script that needed them, and with OpenBLAS defaulting to all cores across concurrent
    jobs that stretched to hours.  The result is fully determined by its arguments, so it
    is cached under results/cache/ and keyed by a digest of the matrices themselves.
    """
    cache_path = os.path.join(CACHE, _ds_key(n_samples, Gb, Gs,
                                             incident_fields(pts, dirs, kb),
                                             nx, ny, seed, snr_db) + ".npz")
    if cache and os.path.exists(cache_path):
        try:
            z = np.load(cache_path)
            chis, ys, Ei_ = z["chis"], z["ys"], z["Ei"]
            if chis.shape[0] != n_samples or Ei_.shape != (len(dirs), nx * ny):
                raise ValueError("stale cache entry: %s" % (chis.shape,))
            return chis, ys, Ei_
        except Exception:
            pass                                    # unreadable cache -> regenerate
    rng = np.random.default_rng(seed)
    Ei = incident_fields(pts, dirs, kb)
    chis, ys = [], []
    for _ in range(n_samples):
        chi = random_contrast(nx, ny, rng)
        _, _, y = forward_exact(Gb, Gs, Ei, chi)
        ys.append(add_noise(y, snr_db, rng))
        chis.append(chi)
    chis = np.stack(chis).astype(np.float32)
    ys = np.stack(ys).astype(np.complex64)
    Ei = np.asarray(Ei)
    if cache:
        try:
            os.makedirs(CACHE, exist_ok=True)
            tmp = cache_path + ".tmp%d" % os.getpid()
            # numpy appends ".npz" to a *string* path, which would make os.replace look
            # for a file that does not exist; writing through a handle pins the name.
            with open(tmp, "wb") as fh:
                np.savez_compressed(fh, chis=chis, ys=ys, Ei=Ei)
            os.replace(tmp, cache_path)          # atomic: concurrent writers cannot
            globals()["_CACHE_WRITES"] = globals().get("_CACHE_WRITES", 0) + 1
        except Exception:                        # leave a half-written zip behind
            pass
            pass                                    # a read-only FS must not break a run
    return chis, ys, Ei

# ----------------------------------------------------------------- model ----

def _power_sigma(W, iters=8):
    """Largest singular value of real matrix W via power iteration (no grad)."""
    with torch.no_grad():
        u = torch.randn(W.shape[1], device=W.device)
        for _ in range(iters):
            v = W @ u
            v = v / (v.norm() + 1e-12)
            u = W.T @ v
            u = u / (u.norm() + 1e-12)
        return (W @ u).norm()

class SpecConv(nn.Module):
    """Conv2d with optional hard spectral-norm clamp (rescale if sigma > 1)."""
    def __init__(self, cin, cout, k=3, sn=True):
        super().__init__()
        self.conv = nn.Conv2d(cin, cout, k, padding=k // 2)
        self.sn = sn

    def clamp_sn(self):
        if not self.sn:
            return
        p = self.conv.weight
        W = p.reshape(p.shape[0], -1)
        sigma = _power_sigma(W)
        if sigma > 1.0:
            with torch.no_grad():
                p.data = (W / sigma).reshape(p.shape)

    def forward(self, x):
        return self.conv(x)

class CorrectionNet(nn.Module):
    """H_k: feature map (B,C,nx,ny) -> delta chi (B,1,nx,ny)."""
    def __init__(self, cin, width=8, constrained=True, eps_bar=0.05):
        super().__init__()
        self.c1 = SpecConv(cin, width, sn=constrained)
        self.c2 = SpecConv(width, width, sn=constrained)
        self.c3 = SpecConv(width, 1, sn=constrained)
        self.constrained = constrained
        self.eps_bar = eps_bar

    def forward(self, feat):
        h = F.relu(self.c1(feat))
        h = F.relu(self.c2(h))
        d = self.c3(h)
        if self.constrained:
            d = self.eps_bar * torch.tanh(d)
        return d

    def clamp_sn(self):
        if self.constrained:
            self.c1.clamp_sn(); self.c2.clamp_sn(); self.c3.clamp_sn()

class UnrolledISP(nn.Module):
    def __init__(self, K, Gb, Gs, Ei, nx, ny, n_inc, mode="constrained",
                 eps_bar=0.03, den_eps=1e-4, a_max=0.5, g_max=0.6, chi_max=0.5,
                 cg_lam_rel=0.05, n_cg=15, lam_rel=0.15, theta=1.0, proj=True,
                 featbound=True):
        super().__init__()
        self.K, self.mode, self.eps_bar = K, mode, eps_bar
        self.den_eps = den_eps
        self.a_max, self.g_max = a_max, g_max
        self.chi_max = chi_max          # physics-prior projection chi in [0, chi_max]
        self.cg_lam_rel = cg_lam_rel
        self.lam_rel = lam_rel
        self.theta = theta
        self.proj = proj                # physics-prior projection switch (ablation)
        self.featbound = featbound      # bounded (1-Lipschitz) state->feature map (ablation)
        self.n_cg = n_cg
        self.nx, self.ny, self.n_inc = nx, ny, n_inc
        self.register_buffer("Gb", torch.as_tensor(Gb, dtype=torch.complex64))
        self.register_buffer("Gs", torch.as_tensor(Gs, dtype=torch.complex64))
        self.register_buffer("Ei", torch.as_tensor(Ei, dtype=torch.complex64))
        gs2 = torch.linalg.matrix_norm(self.Gs, 2) ** 2
        self.register_buffer("c0", (1.0 / gs2).float())   # matched-filter gain 1/||Gs||^2
        if mode != "classical":
            cin = 6 * n_inc + 1                    # per-field: I real + I imag channels; 3 fields + chi
            constrained = (mode == "constrained")
            self.corrs = nn.ModuleList([
                CorrectionNet(cin, constrained=constrained, eps_bar=eps_bar)
                for _ in range(K)])
            self.a = nn.Parameter(torch.full((K,), 0.0))    # sigmoid -> 0.5
            self.g = nn.Parameter(torch.full((K,), 0.0))
            # per-channel feature scales: s_c >= channel Lipschitz bound wrt state
            # (resid_dom: ||Gs||^2 ~ 0.01; E: (1-a)+a*sig(chiGb) <= 1; w: 1; chi: 1)
            s = torch.full((cin,), 2.0)
            s[2 * n_inc:4 * n_inc] = 3.0                    # E channels (via Gb)
            self.register_buffer("feat_scale", s.reshape(1, cin, 1, 1))

    def _Gb_apply(self, w):
        B, I, n = w.shape
        return torch.matmul(self.Gb, w.reshape(-1, n).T).T.reshape(B, I, n)

    def _Gs_apply(self, w):
        B, I, n = w.shape
        return torch.matmul(self.Gs, w.reshape(-1, n).T).T.reshape(B, I, -1)

    def _cg_ls(self, E, y, n_cg=15, lam_rel=1e-2):
        """Regularized least-squares contrast solve via CG on
        A x = b,  A = Re sum_i diag(conj E_i) Gs^H Gs diag(E_i) + lam I,
        b = Re sum_i conj(E_i) Gs^H y_i.  lam = lam_rel * (max eig proxy).
        Returns x (B,n). Real symmetric PSD system -> CG valid."""
        B = E.shape[0]

        def apply_A(x):
            Ex = E * x.unsqueeze(1)                       # (B,I,n)
            m = torch.matmul(self.Gs, Ex.reshape(-1, Ex.shape[-1]).T).T.reshape(B, E.shape[1], -1)
            Gm = torch.matmul(self.Gs.conj().T, m.reshape(-1, m.shape[-1]).T).T.reshape(E.shape)
            val = (E.conj() * Gm).real.sum(dim=1)
            return val + self.cg_lam_rel * 0 * val        # lam handled outside

        b = (E.conj() * torch.matmul(
            self.Gs.conj().T, y.reshape(-1, y.shape[-1]).T).T.reshape(E.shape)).real.sum(dim=1)
        # diag(A)_j = sum_i |E_ij|^2 (Gs^HGs)_jj, (Gs^HGs)_jj = ||Gs[:,j]||^2
        if not hasattr(self, "_gs_diag"):
            self._gs_diag = (torch.abs(self.Gs) ** 2).sum(dim=0)     # (n,)
        diagA = ((torch.abs(E) ** 2) * self._gs_diag).sum(dim=1)  # (B,n)
        lam = self.cg_lam_rel * diagA + 1e-12
        x = torch.zeros_like(b)
        r = b.clone()
        p = r.clone()
        rs = (r * r).sum(dim=1)
        for _ in range(n_cg):
            Ap = apply_A(p) + lam * p
            pAp = (p * Ap).sum(dim=1).clamp_min(1e-20)
            alpha = (rs / pAp).unsqueeze(1)
            x = x + alpha * p
            r = r - alpha * Ap
            rs_new = (r * r).sum(dim=1)
            beta = (rs_new / rs.clamp_min(1e-20)).unsqueeze(1)
            p = r + beta * p
            rs = rs_new
        return x

    def layer(self, k, chi, w, y):
        B = chi.shape[0]
        if self.mode == "classical":
            alpha = gamma = torch.tensor(1.0, device=chi.device)
            theta = 1.0
        else:
            alpha = self.a_max * torch.sigmoid(self.a[k])
            gamma = self.g_max * torch.sigmoid(self.g[k])
            theta = self.theta
        w_t = (1 - alpha) * w + alpha * chi.unsqueeze(1) * (self.Ei.unsqueeze(0) + self._Gb_apply(w))
        E = self.Ei.unsqueeze(0) + self._Gb_apply(w_t)
        # regularized LS contrast solve via CG (exact algebraic step; the state
        # sensitivity of this step is handled by the chi-projection + budgets)
        chi_hat = self._cg_ls(E, y)
        chi_t = (1 - gamma) * chi + gamma * chi_hat
        if self.mode != "classical":
            resid = self._Gs_apply(w_t) - y                                    # (B,I,n_rx)
            resid_dom = torch.matmul(self.Gs.conj().T, resid.reshape(-1, resid.shape[-1]).T).T.reshape(B, self.n_inc, -1)
            feat = torch.cat([
                resid_dom.real.reshape(B, -1), resid_dom.imag.reshape(B, -1),
                E.real.reshape(B, -1), E.imag.reshape(B, -1),
                w_t.real.reshape(B, -1), w_t.imag.reshape(B, -1),
                chi], dim=1)
            feat = feat.reshape(B, -1, self.nx, self.ny)
            if self.featbound:
                feat = torch.tanh(feat / self.feat_scale)   # saturating, Lip<=1, range<=1
            else:
                feat = feat / self.feat_scale               # same normalisation, no saturation
            dchi = self.corrs[k](feat).flatten(1)
        else:
            dchi = 0.0
        # global relaxation theta: preserves fixed points, enforces measured
        # composite gain <= rho_tg (Thm.1 hypothesis), price = slower per-layer progress
        chi_out = chi + self.theta * (chi_t - chi) + dchi
        w_out = w + self.theta * (w_t - w)
        if self.proj:
            chi_out = chi_out.clamp(0.0, self.chi_max)  # physics prior: passive dielectric
        return chi_out, w_out

    def forward(self, chi0, w0, y):
        chi, w = chi0, w0
        for k in range(self.K):
            chi, w = self.layer(k, chi, w, y)
        return chi, w

    def clamp_sn(self):
        if self.mode == "constrained":
            for c in self.corrs:
                c.clamp_sn()

def estimate_gain(model, k, chi, w, y, n_trials=6, eps=1e-3, seed=0):
    """Empirical local gain: sup over random unit directions of
    ||layer(z+eps*d) - layer(z-eps*d)|| / (2*eps). chi real, w complex."""
    g = torch.Generator().manual_seed(seed + 7919 * (k + 1))
    best = 0.0
    for _ in range(n_trials):
        dchi = torch.randn(chi.shape, generator=g).to(chi.device)
        dwr = torch.randn(w.shape, generator=g).to(w.device)
        dwi = torch.randn(w.shape, generator=g).to(w.device)
        nrm = torch.sqrt((dchi ** 2).sum() + (dwr ** 2).sum() + (dwi ** 2).sum()) + 1e-12
        dchi, dwr, dwi = dchi / nrm, dwr / nrm, dwi / nrm
        with torch.no_grad():
            o1 = model.layer(k, chi + eps * dchi, w + eps * (dwr + 1j * dwi), y)
            o2 = model.layer(k, chi - eps * dchi, w - eps * (dwr + 1j * dwi), y)
            dc = (o1[0] - o2[0]) ** 2
            dw = (o1[1] - o2[1]).abs() ** 2
            gain = torch.sqrt((dc.sum() + dw.sum()) / (4 * eps * eps)).item()
        best = max(best, gain)
    return best

def _flat_layer_fn(model, k, y):
    """f: flat real state (B, n(1+2I)) -> flat real state. Real wrap of layer k."""
    B = y.shape[0]
    n = model.nx * model.ny
    I = model.n_inc

    def f(zr):
        chi = zr[:, :n]
        wr = zr[:, n:n + n * I].reshape(B, I, n)
        wi = zr[:, n + n * I:].reshape(B, I, n)
        chi2, w2 = model.layer(k, chi, wr + 1j * wi, y)
        return torch.cat([chi2, w2.real.reshape(B, -1), w2.imag.reshape(B, -1)], dim=1)
    return f

def _power_sigma_fd(f, zr, in_mask=None, out_slice=None, iters=12, eps=1e-3):
    """sigma_max of J restricted to input columns in_mask and output rows out_slice."""
    z = zr.clone().detach()
    z.requires_grad_(True)
    D = z.shape[1]
    idx_in = torch.arange(D, device=z.device) if in_mask is None else in_mask
    rows = slice(0, D) if out_slice is None else out_slice
    u = torch.zeros_like(z)
    u[:, idx_in] = torch.randn(len(idx_in), device=z.device)
    u = u / (u.norm() + 1e-12)
    sig = 0.0
    for _ in range(iters):
        with torch.no_grad():
            Ju = (f(z + eps * u) - f(z - eps * u)) / (2 * eps)
            Ju = Ju[:, rows]
            nv = Ju.norm() + 1e-12
            v_full = torch.zeros_like(z)
            v_full[:, rows] = Ju / nv
        with torch.enable_grad():
            g = torch.autograd.grad(f(z), (z,), grad_outputs=v_full)[0]
        gu = g[:, idx_in]
        nu = gu.norm()
        if nu < 1e-12:
            break
        u = torch.zeros_like(z)
        u[:, idx_in] = gu / nu
        sig = nv
    return float(sig)

def exact_cycle_rho(model, chi, w, y, m=25, eps=1e-3):
    """Spectral radius estimate of the cyclic composite Jacobian at (chi,w):
    rho ~ ||J^m u||^{1/m} via repeated FD linearized applications at the same point."""
    K = model.K
    B = y.shape[0]
    n = model.nx * model.ny
    I = model.n_inc

    def f(zr):
        chi = zr[:, :n]
        wr = zr[:, n:n + n * I].reshape(B, I, n)
        wi = zr[:, n + n * I:].reshape(B, I, n)
        c, ww = chi, wr + 1j * wi
        for k in range(K):
            c, ww = model.layer(k, c, ww, y)
        return torch.cat([c, ww.real.reshape(B, -1), ww.imag.reshape(B, -1)], dim=1)

    zr = torch.cat([chi, w.real.reshape(chi.shape[0], -1),
                    w.imag.reshape(chi.shape[0], -1)], dim=1).detach()
    with torch.no_grad():
        f0 = f(zr)
        u = torch.randn_like(zr)
        u = u / (u.norm() + 1e-12)
        nrm0 = 1.0
        for i in range(m):
            Ju = (f(zr + eps * u) - f(zr - eps * u)) / (2 * eps)
            nv = Ju.norm() + 1e-12
            u = Ju / nv
            nrm0 = nv
    return float(nrm0 ** (1.0 / m))

def exact_gain(model, k, chi, w, y, iters=12):
    """Exact spectral norm of the layer-k Jacobian (realified state)."""
    f = _flat_layer_fn(model, k, y)
    zr = torch.cat([chi, w.real.reshape(chi.shape[0], -1),
                    w.imag.reshape(chi.shape[0], -1)], dim=1).detach()
    return _power_sigma_fd(f, zr, iters=iters)

def exact_cycle_gain(model, chi, w, y, K=None, iters=12):
    """Spectral norm of the composite Jacobian over all K layers."""
    K = K or model.K
    B = y.shape[0]
    n = model.nx * model.ny
    I = model.n_inc

    def f(zr):
        chi = zr[:, :n]
        wr = zr[:, n:n + n * I].reshape(B, I, n)
        wi = zr[:, n + n * I:].reshape(B, I, n)
        c, ww = chi, wr + 1j * wi
        for k in range(K):
            c, ww = model.layer(k, c, ww, y)
        return torch.cat([c, ww.real.reshape(B, -1), ww.imag.reshape(B, -1)], dim=1)

    zr = torch.cat([chi, w.real.reshape(chi.shape[0], -1),
                    w.imag.reshape(chi.shape[0], -1)], dim=1).detach()
    return _power_sigma_fd(f, zr, iters=iters)
